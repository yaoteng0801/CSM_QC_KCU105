// Ethernet hierarchy and interfaces:
//
//   Parent: tdc_decoder_top.data_packet_inst
//   Children: none; this module is the detector hit-frame byte serializer
//
//   TDC event FIFO, read in the 125 MHz TX domain
//                         |
//                         v
//                    data_packet
//                         |
//                         v
//   minidaq_ethernet_subsystem hit input -> tx_qos -> TEMAC TX
//
// This module produces only the 0x0068 detector-data frame. Programming,
// control, and monitoring frames are generated by separate Ethernet modules.
// The parent subsystem applies occupancy-aware arbitration and propagates
// TEMAC backpressure to this module through tx_axis_fifo_tready.


module data_packet (
  input clk,    // Clock 125MHz

  input rst,  // Asynchronous reset active high

  input enable,

  input [39:0] TDC_fifo_data, //from TDC fifo
  input TDC_data_ready,
  output reg TDC_data_rd,

  //to ethernet interface tx_axis_fifo     
  output reg [7:0] data_to_eth,
  output reg packet_valid,
  input tx_axis_fifo_tready,
  output reg last
  
);




reg [39:0] TDC_data_reg;
reg [15:0] counter;
reg [15:0] packet_counter;
reg [3:0] data_flag;


localparam IDLE = 4'b0001,
           STARTPRE = 4'b0010,
           DATA = 4'b0100,
           LAST = 4'b1000;


// Ethernet client frame:
// Do not send the seven-byte preamble (55:55:55:55:55:55:55) or the SFD
// (D5) on this AXI-Stream interface.  The TEMAC inserts both before DSTADDR
// on RGMII, and the receiving NIC strips both before delivering the frame to
// libpcap.  Ethernet FCS coverage starts at DSTADDR, not at the preamble/SFD.
// Supplying PRE/SFD here would make the TEMAC interpret them as MAC-header
// bytes and would create a malformed frame with a second TEMAC-generated
// preamble/SFD in front.
// localparam PRE = 56'h55555555555555; // physical-wire value; TEMAC generated
// localparam SFD = 8'hD5;              // physical-wire value; TEMAC generated
// Transmitted as bytes 0..5 of every frame.  The TEMAC does not verify or
// rewrite this destination.  MiniDAQ's libpcap capture currently uses
// promiscuous mode, so this value is not required to match the receiving
// NIC's MAC address.  Without promiscuous mode, set this to the receiver MAC.
localparam DSTADDR = 48'he8393563c6c1;
// Transmitted as bytes 6..11 of every frame.  The host capture selects frames
// with BPF filter "ether src 02:00:00:c7:05:01" in GUI_DAQ/tab_capture.py,
// GUI_DAQ/capture_settings.ini, and the legacy DAQ capture sources.  Update
// those filters whenever SRCADDR changes.  The first octet 0x02 has I/G=0 and
// U/L=1, making this a legal locally administered unicast source address.  Keep
// the complete address unique if multiple MiniDAQ transmitters share a LAN.
localparam SRCADDR = 48'h020000C70501;
localparam [15:0] TDC_DATA_BYTE_COUNT = 16'd100; // twenty 40-bit TDC words
localparam [15:0] TRAILER_BYTE_COUNT = 16'd4;
// IEEE 802.3 Length counts all client payload bytes, but excludes the
// 14-byte MAC header and the FCS generated by the TEMAC.
localparam [15:0] ETHERNET_PAYLOAD_LENGTH =
    TDC_DATA_BYTE_COUNT + TRAILER_BYTE_COUNT;
localparam [15:0] TRAILER_RESERVED = 16'h0000;

localparam [15:0] HEADER_BYTE_COUNT = 16'd14;



    
    
reg [3:0] state, next;

//state machine


reg  [111:0] preload;
reg  [31:0]  application_trailer;

always @(posedge clk) begin
  if(rst) state <= IDLE;
  else    state <= next;
end



always @(*) begin   
  next = IDLE;
  data_to_eth = 8'b0;
  last = 1'b0;
  packet_valid = 1'b1;
  case (state)
    IDLE: begin
      packet_valid = 1'b0;
      if(TDC_data_ready&enable) next = STARTPRE;
      else                      next = IDLE;
    end
    STARTPRE: begin
      data_to_eth = preload[111:104];
      // Advance only after the current AXI-Stream byte is accepted.
      // If TREADY is low on the final header byte, hold the state and
      // keep TDATA/TVALID stable until the handshake completes.
      if((counter >= HEADER_BYTE_COUNT) && tx_axis_fifo_tready) next = DATA;
      else                                                     next = STARTPRE;
    end
    DATA:begin
      data_to_eth = TDC_data_reg[39:32];
      // The final TDC-data byte must be accepted before entering the
      // application-trailer state.
      if((counter >= TDC_DATA_BYTE_COUNT) && tx_axis_fifo_tready) next = LAST;
      else                                                       next = DATA;
    end
    LAST:begin
      data_to_eth = application_trailer[31:24];
      if(counter < TRAILER_BYTE_COUNT) begin
        next = LAST;
      end else begin
        // TLAST belongs to the final byte.  Hold both TLAST and that byte
        // while stalled; return to IDLE only after TREADY accepts them.
        last = 1'b1;
        if(tx_axis_fifo_tready) next = IDLE;
        else                    next = LAST;
      end
    end
  endcase // state
end

reg [3:0] data_counter = 4'b1;
always @(posedge clk) begin
  if(rst) begin
    counter <= 16'b0;
    data_counter <= 4'b1;
    packet_counter <= 16'b0;
  end else begin

    TDC_data_rd <= 1'b0;
    case (state)
      IDLE: begin 
        counter <= 16'b0;
        preload <= {DSTADDR,SRCADDR,ETHERNET_PAYLOAD_LENGTH};
        application_trailer <= {TRAILER_RESERVED,packet_counter};
        if(TDC_data_ready&enable) begin
          counter <= 1'b1;
          TDC_data_reg <= TDC_fifo_data; //preload the first TDC data
          TDC_data_rd <= 1'b1;
          packet_counter <= packet_counter +1'b1;
        end

      end
      STARTPRE:
        if(tx_axis_fifo_tready) begin
          counter <= counter==HEADER_BYTE_COUNT? 16'b1 : counter +1'b1;
          preload <= {preload[103:0],preload[111:104]};
        end
        
      DATA:begin
        if(tx_axis_fifo_tready) begin
          counter <= counter==TDC_DATA_BYTE_COUNT? 16'b1 : counter + 1'b1;
          if(data_counter==5) begin   //one 40bit TDC data read finish
            data_counter <= 8'b1;
            if(TDC_data_ready) begin
              TDC_data_reg <= TDC_fifo_data;
              if(counter==TDC_DATA_BYTE_COUNT) TDC_data_rd <=1'b0;//last load, no read from TDC fifo
              else                             TDC_data_rd <= 1'b1;
            end else TDC_data_reg <= 40'hFFFFFFFFFF;
          end else begin
            data_counter <= data_counter + 1'b1;
            TDC_data_reg <= {TDC_data_reg[31:0],TDC_data_reg[39:32]};
          end
        end
      end
      LAST:
        if(tx_axis_fifo_tready) begin
          counter <= counter==TRAILER_BYTE_COUNT? 16'b1 : counter +1'b1;
          application_trailer <= {application_trailer[23:0],
                                  application_trailer[31:24]};
        end
    
    endcase
  end
end
